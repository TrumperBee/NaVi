import 'package:latlong2/latlong.dart';

class StageData {
  final String id;
  final String name;
  final double lat;
  final double lng;
  final String corridorId;
  final List<String> routeNumbers;
  final String? area;
  final List<String>? saccos;
  final double? averageFare;

  /// Optional link to a named place (spec §1.2). Most seed/imported stops
  /// have no place; only unambiguous near-name + proximity matches get one.
  final String? placeId;

  const StageData({
    required this.id,
    required this.name,
    required this.lat,
    required this.lng,
    required this.corridorId,
    required this.routeNumbers,
    this.area,
    this.saccos,
    this.averageFare,
    this.placeId,
  });

  LatLng get location => LatLng(lat, lng);
}

