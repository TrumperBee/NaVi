// Helper functions for easy access
List<StageData> getStagesByCorridor(String corridorId) {
  return nairobiStages.where((s) => s.corridorId == corridorId).toList();
}

StageData? findStageById(String id) {
  try {
    return nairobiStages.firstWhere((s) => s.id == id);
  } catch (_) {
    return null;
  }
}

List<StageData> findStagesByName(String query) {
  final lower = query.toLowerCase().trim();
  return nairobiStages.where((s) =>
    s.name.toLowerCase().contains(lower) ||
    s.area?.toLowerCase().contains(lower) == true
  ).toList();
}